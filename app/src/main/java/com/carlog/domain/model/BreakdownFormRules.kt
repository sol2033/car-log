package com.carlog.domain.model

import com.carlog.util.toMileageOrNull

/**
 * Правила формы обслуживания, от которых зависит, сохранится ли запись.
 *
 * Чистые функции без IO (правило 9): здесь живут ровно те проверки, из-за которых правка
 * молча не доезжала до базы — необработанный разбор пробега и валидация, намертво
 * блокировавшая запись с битыми ссылками на запчасти.
 */
object BreakdownFormRules {

    /**
     * Ошибка поля «Пробег».
     *
     * Проверки на пустоту было мало: следом шёл `toInt()`, и любое нечисловое значение
     * роняло сохранение в `catch`. Пользователь видел красным текст java-исключения
     * по-английски — и запись, разумеется, не сохранялась.
     */
    fun mileageError(raw: String): String? = when {
        raw.isBlank() -> "Обязательное поле"
        raw.toMileageOrNull() == null -> "Пробег вводится целым числом"
        else -> null
    }

    /**
     * Включать ли режим «запчасти списком» при загрузке сохранённого события.
     *
     * Решают **загруженные** запчасти, а не ссылки на них: удаление запчасти в модуле
     * «Запчасти» не чистит `Breakdown.installedPartIds`, и по повисшим ссылкам режим
     * включался с пустым списком. Дальше валидация «добавьте хотя бы одну запчасть»
     * не давала сохранить запись вообще — на экране это выглядело как «жму сохранить,
     * ничего не происходит»: сообщение оставалось за пределами видимой части формы.
     */
    fun usesPartsList(loadedParts: List<Part>): Boolean = loadedParts.isNotEmpty()
}
