package com.carlog.domain.model

/**
 * Отдельная работа внутри обслуживания (ТО, ремонт, тюнинг): «замена масла», «развал-схождение».
 *
 * Хранится списком прямо в записи обслуживания (`Breakdown.workItems`, JSON через `Converters`),
 * а не отдельной таблицей: работы никуда не «выходят» — своего раздела у них нет, с другими
 * модулями они не связываются, файлов не имеют и удаляются вместе с обслуживанием.
 *
 * Сумма стоимостей работ кладётся в `Breakdown.serviceCost`, поэтому вся статистика
 * («Услуги сервисов», «Запчасти vs Работа») считается по-прежнему и задвоиться не может.
 */
data class WorkItem(
    val name: String,
    val cost: Double,
    val notes: String? = null
)

/** Итого по работам — эта сумма и есть стоимость работ обслуживания */
fun List<WorkItem>.totalCost(): Double = sumOf { it.cost }
